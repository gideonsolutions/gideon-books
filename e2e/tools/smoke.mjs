import { chromium } from "@playwright/test";
const sp = process.argv[2];
const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const email = `smoke-${Date.now()}@example.test`;
await page.goto("http://localhost:3200/sign-up");
await page.getByLabel("Your name").fill("Smoke Tester");
await page.getByLabel("Email").fill(email);
await page.getByLabel("Password").fill("correct horse battery staple");
await page.getByRole("button", { name: "Create account" }).click();
await page.waitForURL("**/orgs/new");
await page.getByLabel("Organization name").fill("Smoke Test LLC");
await page.getByRole("button", { name: "Create and continue" }).click();
await page.waitForURL("**/onboarding", { timeout: 15000 }).catch(() => {});
console.log("after create:", page.url());
const slug = page.url().split("/o/")[1]?.split("/")[0];
await page.goto(`http://localhost:3200/o/${slug}/accounting/accounts`);
await page.screenshot({ path: `${sp}/accounts.png`, fullPage: false });
await page.goto(`http://localhost:3200/o/${slug}/accounting/journal/new`);
await page.screenshot({ path: `${sp}/journal-new.png`, fullPage: false });
console.log(slug);
await browser.close();
